import java.io.IOException;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.nio.file.Paths;
import java.util.ArrayList;
import java.util.List;
import java.util.Locale;

// Bundles the per-run SSE logs and the final metrics table in results/ into a single
// JSON file for charting, plus a JS wrapper so viewer/index.html can be opened
// straight off the filesystem (browsers block fetch() on file:// URLs).
//
// Run from the repository root with no compile step:
//     java tools/BundleResults.java
//
// Reads:  results/metrics_summary.csv, results/SSE_Log_<label>.csv
// Writes: viewer/results-bundle.json, viewer/results-bundle.js

public class BundleResults {

    static final long SEED = 1541928603L;
    static final int MAX_EPOCHS = 500;

    // Each run varies one factor against the reference configuration. The group is
    // derived from the run label so the viewer can offer the ablation as facets.
    static String groupFor(String label) {
        if (label.startsWith("lr_")) return "learning rate";
        if (label.startsWith("decay_")) return "decay";
        if (label.startsWith("init_")) return "initialisation";
        if (label.startsWith("hidden_")) return "hidden units";
        if (label.startsWith("earlystop")) return "early stopping";
        return "baseline";
    }

    // One row of results/metrics_summary.csv joined to its per-epoch curve.
    static class Run {
        String label, group, init;
        int hidden, patience, epochsRun;
        double learningRate, decay;
        double trainSSE, valSSE, testSSE, trainAccuracy, testAccuracy;
        boolean earlyStopping;
        List<Integer> epoch = new ArrayList<>();
        List<Double> trainCurve = new ArrayList<>();
        List<Double> valCurve = new ArrayList<>();
        List<Double> lrCurve = new ArrayList<>();
    }

    public static void main(String[] args) throws IOException {
        Path root = Paths.get("").toAbsolutePath();
        Path results = root.resolve("results");
        Path viewer = root.resolve("viewer");

        if (!Files.isDirectory(results)) {
            System.err.println("No results/ directory found. Run this from the repository root.");
            System.exit(1);
        }
        Files.createDirectories(viewer);

        List<Run> runs = readMetrics(results.resolve("metrics_summary.csv"));

        for (Run run : runs) {
            Path curve = results.resolve("SSE_Log_" + run.label + ".csv");
            if (!Files.exists(curve)) {
                System.out.printf("  warning: no SSE log for run '%s', curve will be empty%n", run.label);
                continue;
            }
            readCurve(curve, run);
        }

        // Flag any SSE log that has no matching row in the metrics table, so an
        // orphaned or duplicated log does not silently disappear from the bundle.
        try (var listing = Files.list(results)) {
            listing.map(p -> p.getFileName().toString())
                    .filter(n -> n.startsWith("SSE_Log_") && n.endsWith(".csv"))
                    .map(n -> n.substring("SSE_Log_".length(), n.length() - ".csv".length()))
                    .filter(label -> runs.stream().noneMatch(r -> r.label.equals(label)))
                    .forEach(label -> System.out.printf(
                            "  note: SSE_Log_%s.csv has no row in metrics_summary.csv, skipped%n", label));
        }

        String json = toJson(runs);
        Files.writeString(viewer.resolve("results-bundle.json"), json, StandardCharsets.UTF_8);
        Files.writeString(viewer.resolve("results-bundle.js"),
                "// Generated by tools/BundleResults.java. Do not edit by hand.\n"
                        + "window.RESULTS_BUNDLE = " + json + ";\n",
                StandardCharsets.UTF_8);

        int points = runs.stream().mapToInt(r -> r.epoch.size()).sum();
        System.out.printf("Bundled %d runs (%d epoch records) into:%n", runs.size(), points);
        System.out.println("  viewer/results-bundle.json");
        System.out.println("  viewer/results-bundle.js");
    }

    // results/metrics_summary.csv:
    // Label,Hidden,LearningRate,Decay,Init,Patience,EpochsRun,TrainSSE,TestSSE,TrainPctCorrect,TestPctCorrect,ValSSE
    static List<Run> readMetrics(Path file) throws IOException {
        List<String> lines = Files.readAllLines(file, StandardCharsets.UTF_8);
        List<Run> runs = new ArrayList<>();
        for (int i = 1; i < lines.size(); i++) {
            String line = lines.get(i).trim();
            if (line.isEmpty()) continue;
            String[] c = line.split(",");
            if (c.length < 12) {
                System.out.printf("  warning: skipping malformed metrics row %d%n", i + 1);
                continue;
            }
            Run r = new Run();
            r.label = c[0].trim();
            r.group = groupFor(r.label);
            r.hidden = Integer.parseInt(c[1].trim());
            r.learningRate = Double.parseDouble(c[2].trim());
            r.decay = Double.parseDouble(c[3].trim());
            r.init = c[4].trim();
            r.patience = Integer.parseInt(c[5].trim());
            r.epochsRun = Integer.parseInt(c[6].trim());
            r.trainSSE = Double.parseDouble(c[7].trim());
            r.testSSE = Double.parseDouble(c[8].trim());
            r.trainAccuracy = Double.parseDouble(c[9].trim());
            r.testAccuracy = Double.parseDouble(c[10].trim());
            r.valSSE = Double.parseDouble(c[11].trim());
            // A patience at or above the epoch cap can never fire, so those runs
            // trained the full schedule with early stopping effectively off.
            r.earlyStopping = r.patience < MAX_EPOCHS;
            runs.add(r);
        }
        return runs;
    }

    // results/SSE_Log_<label>.csv: Epoch,TrainSSE,ValSSE,LearningRate
    static void readCurve(Path file, Run run) throws IOException {
        List<String> lines = Files.readAllLines(file, StandardCharsets.UTF_8);
        for (int i = 1; i < lines.size(); i++) {
            String line = lines.get(i).trim();
            if (line.isEmpty()) continue;
            String[] c = line.split(",");
            if (c.length < 4) continue;
            run.epoch.add(Integer.parseInt(c[0].trim()));
            run.trainCurve.add(Double.parseDouble(c[1].trim()));
            run.valCurve.add(Double.parseDouble(c[2].trim()));
            run.lrCurve.add(Double.parseDouble(c[3].trim()));
        }
    }

    // Minimal JSON writer. Curves are parallel arrays rather than an array of
    // objects, which keeps the bundle small and maps straight onto a chart series.
    static String toJson(List<Run> runs) {
        StringBuilder sb = new StringBuilder();
        sb.append("{\n");
        sb.append("  \"methodology\": {\n");
        sb.append("    \"seed\": ").append(SEED).append(",\n");
        sb.append("    \"split\": \"70/15/15 train/validation/test, uniform random shuffle\",\n");
        sb.append("    \"trainSize\": 8618,\n");
        sb.append("    \"validationSize\": 1847,\n");
        sb.append("    \"testSize\": 1846,\n");
        sb.append("    \"scaling\": \"z-score, fitted on the training set only\",\n");
        sb.append("    \"maxEpochs\": ").append(MAX_EPOCHS).append(",\n");
        sb.append("    \"errorMeasure\": \"Sum Squared Error\"\n");
        sb.append("  },\n");
        sb.append("  \"reference\": {\n");
        sb.append("    \"hidden\": 32,\n");
        sb.append("    \"learningRate\": 0.10,\n");
        sb.append("    \"decay\": 0.95,\n");
        sb.append("    \"init\": \"faninit\",\n");
        sb.append("    \"patience\": 20\n");
        sb.append("  },\n");
        sb.append("  \"runs\": [\n");
        for (int i = 0; i < runs.size(); i++) {
            Run r = runs.get(i);
            sb.append("    {\n");
            sb.append("      \"label\": \"").append(escape(r.label)).append("\",\n");
            sb.append("      \"group\": \"").append(escape(r.group)).append("\",\n");
            sb.append("      \"hidden\": ").append(r.hidden).append(",\n");
            sb.append("      \"learningRate\": ").append(num(r.learningRate)).append(",\n");
            sb.append("      \"decay\": ").append(num(r.decay)).append(",\n");
            sb.append("      \"init\": \"").append(escape(r.init)).append("\",\n");
            sb.append("      \"patience\": ").append(r.patience).append(",\n");
            sb.append("      \"earlyStopping\": ").append(r.earlyStopping).append(",\n");
            sb.append("      \"epochsRun\": ").append(r.epochsRun).append(",\n");
            sb.append("      \"trainSSE\": ").append(num(r.trainSSE)).append(",\n");
            sb.append("      \"valSSE\": ").append(num(r.valSSE)).append(",\n");
            sb.append("      \"testSSE\": ").append(num(r.testSSE)).append(",\n");
            sb.append("      \"trainAccuracy\": ").append(num(r.trainAccuracy)).append(",\n");
            sb.append("      \"testAccuracy\": ").append(num(r.testAccuracy)).append(",\n");
            sb.append("      \"epochs\": ").append(ints(r.epoch)).append(",\n");
            sb.append("      \"trainSSE_curve\": ").append(doubles(r.trainCurve)).append(",\n");
            sb.append("      \"valSSE_curve\": ").append(doubles(r.valCurve)).append(",\n");
            sb.append("      \"learningRate_curve\": ").append(doubles(r.lrCurve)).append("\n");
            sb.append("    }").append(i < runs.size() - 1 ? "," : "").append("\n");
        }
        sb.append("  ]\n");
        sb.append("}\n");
        return sb.toString();
    }

    static String ints(List<Integer> values) {
        StringBuilder sb = new StringBuilder("[");
        for (int i = 0; i < values.size(); i++) {
            if (i > 0) sb.append(",");
            sb.append(values.get(i));
        }
        return sb.append("]").toString();
    }

    static String doubles(List<Double> values) {
        StringBuilder sb = new StringBuilder("[");
        for (int i = 0; i < values.size(); i++) {
            if (i > 0) sb.append(",");
            sb.append(num(values.get(i)));
        }
        return sb.append("]").toString();
    }

    // Trim trailing zeros so the bundle stays compact, and never emit a bare
    // trailing dot or an exponent form the JSON parser would choke on.
    static String num(double v) {
        if (Double.isNaN(v) || Double.isInfinite(v)) return "null";
        String s = String.format(Locale.ROOT, "%.6f", v);
        if (s.contains(".")) {
            s = s.replaceAll("0+$", "");
            if (s.endsWith(".")) s = s.substring(0, s.length() - 1);
        }
        return s;
    }

    static String escape(String s) {
        return s.replace("\\", "\\\\").replace("\"", "\\\"");
    }
}
